    @classmethod
    def process_event(cls, sig_id: str, count: int) -> Dict[str, Any]:
        """Evaluate incoming stream signature against rate limit."""
        sig = cls.EVENT_SIGNATURES.get(sig_id)
        if not sig:
            return {'status': 'PASS', 'anomaly': False}
        is_anomaly = count > sig['rate_limit']
        return {
            'status': 'FLAGGED' if is_anomaly else 'PASS',
            'anomaly': is_anomaly,
            'risk_boost': sig['risk_boost'] if is_anomaly else 0.0,
        }

