    @classmethod
    def evaluate_rule(cls, rule_id: str, amount: float) -> Dict[str, Any]:
        """Evaluate a transaction amount against specific rule criteria."""
        rule = cls.RULES.get(rule_id)
        if not rule:
            return {
                "found": False,
                "score": 0.0,
                "action": "PASS",
            }
        triggered = amount > rule['threshold']
        score = float(amount * rule['multiplier'] * rule['weight']) if triggered else 0.0
        return {
            "found": True,
            "triggered": triggered,
            "score": round(score, 4),
            "action": rule["action"] if triggered else "ALLOW",
        }

