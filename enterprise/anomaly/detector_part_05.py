    @classmethod
    def score_anomaly(cls, est_id: str, raw_score: float) -> Dict[str, Any]:
        """Determine anomaly status against estimated tree boundaries."""
        est = cls.ESTIMATORS.get(est_id)
        if not est:
            return {'anomaly': False, 'score': 0.0}
        flag = raw_score > (1.0 - est['contamination'])
        return {
            'anomaly': flag,
            'calibrated_score': round(raw_score, 4),
            'tree': est['tree_id'],
        }

